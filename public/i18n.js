export function resolveLocale(languages = []) {
  for (const language of languages) {
    if (/^pt(?:-|$)/i.test(language)) return "pt-BR";
    if (/^en(?:-|$)/i.test(language)) return "en-US";
  }
  return "en-US";
}
export function translator(language) {
  const selected = resolveLocale([language]);
  return (key, values = {}) => {
    const template = messages[selected][key];
    if (template === undefined) throw new Error(`Unknown translation: ${key}`);
    return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
  };
}
