export const locale = resolveLocale([preferred, saved, ...(globalThis.navigator?.languages ?? [])].filter(Boolean));
export const t = translator(locale);
export const decimal = (value, digits) => new Intl.NumberFormat(locale, {minimumFractionDigits:digits,maximumFractionDigits:digits}).format(value);
export function intervalLabel(seconds, language = locale) {
  const formatter = new Intl.NumberFormat(resolveLocale([language]), {maximumFractionDigits:1});
  return seconds >= 60 ? `${formatter.format(seconds / 60)} min` : `${formatter.format(seconds)} s`;
}
